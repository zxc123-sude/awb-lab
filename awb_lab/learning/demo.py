"""Small synthetic train/validation/test splits for end-to-end smoke tests."""

import csv
from pathlib import Path

import numpy as np

from ..image_io import save_rgb


def make_demo(output_dir, train_count=24, val_count=8, test_count=8, seed=42):
    if any(type(count) is not int or count < 1 for count in (train_count, val_count, test_count)):
        raise ValueError("all demo split counts must be positive integers")
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    rng = np.random.default_rng(seed)
    manifests = {}
    y, x = np.mgrid[:64, :80]
    for split, count in (("train", train_count), ("val", val_count), ("test", test_count)):
        rows = []
        for index in range(count):
            # Each row is an independently generated scene and group. Texture
            # and broad reflectance colors vary independently of illuminant.
            light = np.array([rng.uniform(.65, 1.6), 1., rng.uniform(.65, 1.6)])
            texture = .18 + .08 * np.sin(x / rng.uniform(3, 9) + rng.uniform(0, 6))
            texture += .07 * np.cos(y / rng.uniform(4, 10)) + .08 * x / 79 + .05 * y / 63
            colors = rng.uniform(.8, 1.2, (4, 5, 3))
            colors /= colors.mean(axis=(0, 1), keepdims=True)
            reflectance = np.repeat(np.repeat(colors, 16, axis=0), 16, axis=1) * texture[..., None]
            image = np.clip(reflectance * light, 0, .95)
            mask = np.ones((64, 80), dtype=np.uint8)
            mask[:10, :12] = 0
            image[:10, :12] = [0.85, 0.06, 0.45]
            name = f"{split}_{index:03d}"
            np.save(str(output_dir / f"{name}.npy"), image.astype(np.float32), allow_pickle=False)
            np.save(str(output_dir / f"{name}_mask.npy"), mask, allow_pickle=False)
            if index == 0:
                save_rgb(output_dir / f"{split}_preview.png", image)
            rows.append({"sample_id": name, "image": f"{name}.npy",
                         "illuminant_r": light[0], "illuminant_g": light[1], "illuminant_b": light[2],
                         "black_level": 0, "white_level": 1, "mask": f"{name}_mask.npy",
                         "group_id": f"synthetic_independent_scene_{name}", "camera": "synthetic_diagonal_rgb",
                         "grouping_unit": "independently_generated_synthetic_scene",
                         "split": split, "dataset_type": "synthetic_smoke_test"})
        manifest = output_dir / f"{split}.csv"
        with manifest.open("w", encoding="utf-8", newline="") as handle:
            writer = csv.DictWriter(handle, fieldnames=list(rows[0]))
            writer.writeheader()
            writer.writerows(rows)
        manifests[split] = str(manifest)
    (output_dir / "SYNTHETIC_ONLY.txt").write_text(
        "All images, scenes and illuminants were generated by a simple diagonal RGB model.\n"
        "Train/validation/test are distinct synthetic scenes and groups.\n"
        "These files validate optimization, split checks, checkpointing and inference only.\n"
        "They do not measure camera-RAW accuracy, real-data generalization or paper performance.\n"
        "Training, evaluation and prediction require explicit --allow-synthetic.\n", encoding="utf-8")
    return {"dataset_type": "synthetic_smoke_test", "seed": seed, "manifests": manifests,
            "counts": {"train": train_count, "val": val_count, "test": test_count}}
